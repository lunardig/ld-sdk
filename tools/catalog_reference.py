"""Writes docs/alpha-catalog.md from fixtures/alpha/create.json: every machine with its
ports and processes, every process with its inputs and outputs, every store and kit. Run
it after fixtures/build.py so the reference cannot drift from the catalog.

    python tools/catalog_reference.py
"""
from __future__ import annotations

import json
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))
from ld_client.recipe import recipe  # noqa: E402


def q(x) -> Fraction:
    return Fraction(int(x["n"]), int(x["d"])) if isinstance(x, dict) else Fraction(x)


def num(x: Fraction) -> str:
    if Fraction(x).denominator == 1:
        return f"{int(x):,}"
    return f"{float(x):,.6g}"


def main() -> None:
    c = json.loads((ROOT / "fixtures/alpha/create.json").read_text())
    cat, gen = c["catalog"], c["genesis"]
    units = {u["unit_id"]: u for u in cat["units"]}
    procs = {p["process_id"]: p for p in cat["processes"]}
    out = ["# The alpha catalog", "",
           "Generated by `tools/catalog_reference.py` from `fixtures/alpha/create.json`. Quantities are in each "
           "substance's catalog unit (mmol for most; kg-reg, kilograms, for regolith). Rates are per second unless noted.", ""]
    out += ["## Genesis", "", f"Claim `{gen['claim_id']}` starts at {gen['start_us']} µs with the deposit "
            + ", ".join(f"`{d['deposit_id']}` ({', '.join(f'{v} {k}' for k, v in d['remaining'].items())})" for d in gen["deposits"])
            + " and these lots:", ""]
    for lot in gen["starting_lots"]:
        out.append(f"- `{lot['lot_id']}` at `{lot['location']}`: " + ", ".join(f"{n} × {p}" for p, n in lot["products"].items()))
    fn = next(f for f in cat["environment"] if f["function_id"] == "irradiance")
    dark = next(s for s in fn["segments"] if q(s["value"]) == 0)
    out += ["", f"Sunlight (`irradiance`) is on from 0 to {int(dark['start_us']):,} µs (dusk, {int(dark['start_us']) / 86_400e6:.2f} days) "
            f"and the cycle repeats every {int(fn['period_us']):,} µs ({int(fn['period_us']) / 86_400e6:.2f} days).", ""]

    sites = json.loads((ROOT / "fixtures/alpha/sites.json").read_text())
    out += ["## Sites", "", "A site is a claim's place: it fixes the deposit and the light, and which processes run there (LD-PEC-011). "
            "Choose one at genesis with `alpha(site=...)`, or take the genesis fields from `fixtures/alpha/sites.json`. "
            "Every site is in the one catalog.", "",
            "| Site | Deposit | Light | Solar, dig and sort processes | Ice, ilmenite, silicate (mmol per kg) |", "| --- | --- | --- | --- | --- |"]
    for sid, s in sites.items():
        y, pr = s["yield"], s["processes"]
        out.append(f"| `{sid}`{' (fictional)' if s['fictional'] else ''} | `{s['deposit']}` | `{s['environment']}` | "
                   f"`{pr['solar']}`, `{pr['excavate']}`, `{pr['beneficiate']}` | {y['ice']:,}, {y['ilmenite']:,}, {y['silicate']:,} |")
    out += [""] + [f"- `{sid}`, {s['name']}: {s['summary']}" for sid, s in sites.items()] + [""]

    out += ["## Machines", "", "| Blueprint | Kit | Rated work | Ports | Processes | Notes |", "| --- | --- | --- | --- | --- | --- |"]
    kit_for = {p["installs_as"]["template"]: p["product_id"] for p in cat["products"] if p.get("installs_as")}
    for m in sorted(cat["machines"], key=lambda m: m["blueprint_id"]):
        ports = ", ".join(f"{p['port']} ({p['direction'].lower()}{'' if p['type'] == 'MATERIAL' else ', power'})" for p in m["ports"])
        notes = []
        if m.get("core"):
            notes.append(f"core `{m['core']['buffer']}` on {', '.join(m['core']['ports'])}")
        if m.get("energy_store"):
            es = m["energy_store"]
            notes.append(f"stores {num(q(es['capacity']['amount']))} {es['capacity']['unit']}")
        msr = q(m["min_stable_rate"]) / q(m["rated_work"])
        if msr >= Fraction(1, 100):
            notes.append(f"minimum {num(msr * 100)} % of rated")
        out.append(f"| `{m['blueprint_id']}` | `{kit_for.get(m['blueprint_id'], '—')}` | {num(q(m['rated_work']) * 1_000_000)} work/s | {ports} | "
                   f"{', '.join(f'`{p}`' for p in m['processes']) or '—'} | {'; '.join(notes)} |")

    out += ["", "## Processes", "", "| Process | Mode | Extent unit | Inputs | Outputs | Dispatch |", "| --- | --- | --- | --- | --- | --- |"]
    for pid, p in sorted(procs.items()):
        ins = ", ".join(f"{i['port']}: {'/'.join(i['accepts'])}" for i in p["ports"]["in"]) or "—"
        outs = ", ".join(f"{o['port']}: {'/'.join(o['accepts'])}" for o in p["ports"]["out"]) or "—"
        out.append(f"| `{pid}` | {p['mode']} | {p['extent']['unit']} | {ins} | {outs} | {p.get('dispatch', 'MUST_RUN')} |")
    thr = [(pid, port, t) for pid, p in procs.items() for port, t in p["restart_thresholds"].items()]
    if thr:
        def level(t: dict, key: str) -> str | None:
            if f"{key}_fraction" in t:
                return f"{num(q(t[key + '_fraction']) * 100)} % of the buffer"
            if f"{key}_at" in t:
                return f"{int(t[key + '_at']):,} {t['unit']}"
            return None

        def switch(pid: str, port: str, t: dict) -> str:
            p = procs[pid]
            what = "stock" if any(i["port"] == port for i in p["ports"]["in"]) else "free space"
            s = f"`{pid}` {port} ({what}): restart at {level(t, 'restart')}"
            return s + (f", stop at {level(t, 'stop')}" if level(t, "stop") else "")
        out += ["", "Level switches (LD-PEC-004 A4): a stopped job restarts once the port's level reaches its restart level; a "
                "running one stops at its stop level. An input's level is the stock in its buffer, an output's the free space in "
                "its buffer. " + "; ".join(switch(pid, port, t) for pid, port, t in sorted(thr)) + "."]

    def flows(d: dict) -> str:
        return "; ".join(f"{port}: " + ", ".join(f"{num(v)} {sp}" for sp, v in sorted(m.items())) for port, m in sorted(d.items())) or "—"

    out += ["", "## Recipes", "",
            "Per unit of extent, from `ld_client.recipe(create, process, extent)`, which reads the process's operations "
            "(REACT, PHASE, PARTITION, ASSEMBLE, LOSS) in exact rationals. Work divided by the machine's rated work is the "
            "run time at full rate. Energy is the plain per-work draw, before part-load losses. A FLOW job delivers "
            "fractional outputs as running floors, so whole quantities differ from these by less than one unit.", "",
            "| Process | Draws | Delivers | Makes / loses | Work | Energy |", "| --- | --- | --- | --- | --- | --- |"]
    for pid in sorted(procs):
        r = recipe(c, pid, 1)
        made = ", ".join([f"{num(n)} × {k}" for k, n in r.products.items()]
                         + [f"{num(v)} {sp} to {sink}" for sink, m in r.losses.items() for sp, v in m.items()]) or "—"
        energy = (f"{num(r.energy_drawn_j)} J drawn" if r.energy_drawn_j else "") + \
                 (f"{num(r.energy_produced_j)} J produced" if r.energy_produced_j else "")
        out.append(f"| `{pid}` | {flows(r.inputs)} | {flows(r.outputs)} | {made} | {num(r.work)} | {energy or '—'} |")
    red, fab = recipe(c, "reduce-ilmenite", 400_000), recipe(c, "fabricate-hopper", 1)
    out += ["", "**Sizing a batch, worked.** A reduction batch of extent 400,000 needs "
            f"{num(red.inputs['ilmenite']['fetio3-s'])} mmol of ilmenite and {num(red.inputs['h2']['h2-g'])} mmol of hydrogen in its "
            "input buffers when it starts: a batch captures all its inputs at once; until they are there it is accepted but waits STARVED. Half the ilmenite reacts; the other half comes back through `unreacted`. It delivers "
            f"{num(red.outputs['iron']['fe-s'])} mmol of iron (17/20 of the reduced iron is magnetic), "
            f"{num(red.outputs['water']['h2o-l'])} mmol of water, and rutile carrying the other "
            f"{num(red.outputs['rutile']['fe-s'])} mmol of iron. It dwells {num(red.dwell_us / 1_000_000)} s after its work. "
            f"A hopper kit takes {num(fab.inputs['iron']['fe-s'])} mmol of iron and returns {num(fab.outputs['scrap']['fe-s'])} as scrap, "
            f"so {num(fab.inputs['iron']['fe-s'] / red.outputs['iron']['fe-s'])} such batches make one hopper. "
            "A controller can pull the next batch once its buffers hold `recipe(...).inputs`."]

    out += ["", "## Stores", "", "| Template | Kit | Accepts | Capacity |", "| --- | --- | --- | --- |"]
    for b in sorted(cat["buffers"], key=lambda b: b["template_id"]):
        out.append(f"| `{b['template_id']}` | `{kit_for.get(b['template_id'], '— (part of a machine)')}` | {', '.join(b['accepts'])} | "
                   f"{int(b['capacity']['amount']):,} {b['capacity']['unit']} |")
    out += ["", "## Connections", "", "| Template | Kind | Throughput | Delay |", "| --- | --- | --- | --- |"]
    for t in cat["connections"]:
        out.append(f"| `{t['template_id']}` | {t['kind']} | {num(q(t['throughput']) * 1_000_000)} {t['unit']}/s | {int(t['delay_us']) / 1e6:g} s |")
    out += ["", "## Substances", "", "| Substance | Formula | Phase | Unit |", "| --- | --- | --- | --- |"]
    for s in sorted(cat["substances"], key=lambda s: s["substance_id"]):
        out.append(f"| `{s['substance_id']}` | {' '.join(f'{e}{n}' for e, n in s['formula'].items())} | {s['phase']} | {s['quantity_unit']} |")
    (ROOT / "docs/alpha-catalog.md").write_text("\n".join(out) + "\n")
    print("wrote docs/alpha-catalog.md")


if __name__ == "__main__":
    main()
